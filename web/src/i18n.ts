// Page language. UI text lives here; text built by the backend comes back in the language sent with each request.
import { createContext, useContext } from "react";

export type Lang = "zh" | "en";

const LANG_KEY = "playnext.lang";

/** ?lang=en in the link, then the last choice on this browser, then the browser language. */
export function initialLang(): Lang {
  const q = new URLSearchParams(window.location.search).get("lang");
  if (q === "zh" || q === "en") return q;
  try {
    const saved = window.localStorage.getItem(LANG_KEY);
    if (saved === "zh" || saved === "en") return saved;
  } catch {
    /* storage unavailable */
  }
  return (navigator.language || "").toLowerCase().startsWith("zh") ? "zh" : "en";
}

export function saveLang(l: Lang) {
  try {
    window.localStorage.setItem(LANG_KEY, l);
  } catch {
    /* storage unavailable: the choice lasts for this page only */
  }
}

